def _parse(token: str) -> tuple[str, int]:
    caps = [i for i, c in enumerate(token) if c.isupper()]
    if len(caps) != 1 or token[caps[0]].lower() not in VOWELS:
        raise ValueError(f"bad stress mark: {token}")
    return token.lower(), caps[0]


WORDS: list[tuple[str, int]] = list(dict.fromkeys(_parse(t) for t in RAW.split()))
